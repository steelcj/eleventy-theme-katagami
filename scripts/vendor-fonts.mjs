// Copies the theme's fonts from Fontsource packages into themes/katagami/assets/fonts/
// and writes one CSS file per font set into themes/katagami/assets/css/fonts/. The fonts
// and sets are listed in themes/katagami/theme.yaml. Packages are fetched with npm pack
// into a temporary folder, so they never become dependencies. Only the 400 and 700
// weights of each font's listed subsets are kept, with its licence.
// Usage: npm run vendor-fonts

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import yaml from "js-yaml";

const theme = "themes/katagami";
const weights = [400, 700];
const manifest = yaml.load(fs.readFileSync(`${theme}/theme.yaml`, "utf8"));
const work = fs.mkdtempSync(path.join(os.tmpdir(), "katagami-fonts-"));

function fetchPackage(name, version) {
  const output = execFileSync("npm", ["pack", `@fontsource/${name}@${version}`, "--silent", "--pack-destination", work], {
    encoding: "utf8",
  });
  const tarball = output.trim().split("\n").pop();
  const dir = path.join(work, name);
  fs.mkdirSync(dir);
  execFileSync("tar", ["-xzf", path.join(work, tarball), "-C", dir]);
  return path.join(dir, "package");
}

// Copies one font's files into assets/fonts/<name>/ and returns its family name and
// @font-face rules, with Fontsource's unicode ranges, pointing at the copies.
function vendor(name, { version, subsets }) {
  const pkg = fetchPackage(name, version);
  const target = path.join(theme, "assets/fonts", name);
  fs.rmSync(target, { recursive: true, force: true });
  fs.mkdirSync(target, { recursive: true });
  fs.copyFileSync(path.join(pkg, "LICENSE"), path.join(target, "OFL.txt"));
  const faces = [];
  for (const weight of weights) {
    const css = fs.readFileSync(path.join(pkg, `${weight}.css`), "utf8");
    for (const chunk of css.split(/(?=\/\* )/)) {
      const id = chunk.match(/^\/\* (\S+) \*\//)?.[1];
      const subset = id?.slice(name.length + 1, -`-${weight}-normal`.length);
      if (!subsets.includes(subset)) continue;
      const file = chunk.match(/url\(\.\/files\/([^)]+\.woff2)\)/)[1];
      fs.copyFileSync(path.join(pkg, "files", file), path.join(target, file));
      faces.push(
        chunk
          .trim()
          .replace(/font-family: '([^']+)';/, 'font-family: "$1";')
          .replace(/src: [^;]+;/, `src: url("../../fonts/${name}/${file}") format("woff2");`),
      );
    }
  }
  const family = fs.readFileSync(path.join(pkg, "400.css"), "utf8").match(/font-family: '([^']+)'/)[1];
  return { family, faces };
}

const fonts = {};
for (const [name, config] of Object.entries(manifest.fonts)) {
  fonts[name] = { ...config, ...vendor(name, config) };
}

fs.mkdirSync(`${theme}/assets/css/fonts`, { recursive: true });
for (const [set, { heading, body, arabic }] of Object.entries(manifest.fontSets.sets)) {
  const stack = (latin) => `"${fonts[latin].family}", "${fonts[arabic].family}", ${fonts[latin].generic}`;
  const css = [
    `/* The ${set} font set: ${fonts[heading].family} for headings, ${fonts[body].family} for body text,\n   and ${fonts[arabic].family} for Arabic. Generated by scripts/vendor-fonts.mjs from theme.yaml;\n   do not edit. Fonts from Fontsource, under the SIL Open Font License 1.1: see\n   assets/fonts/<font>/OFL.txt. */`,
    ...[...new Set([heading, body, arabic])].flatMap((name) => fonts[name].faces),
    `:root {\n  --font-heading: ${stack(heading)};\n  --font-body: ${stack(body)};\n}`,
  ].join("\n\n");
  fs.writeFileSync(`${theme}/assets/css/fonts/${set}.css`, `${css}\n`);
}

const rows = Object.entries(fonts).map(
  ([name, { family, version, subsets }]) => `| ${family} | \`${name}/\` | ${subsets.join(", ")} | 400, 700 | ${version} |`,
);
fs.writeFileSync(
  `${theme}/assets/fonts/README.md`,
  `# Fonts

These fonts are copied from Fontsource packages by \`scripts/vendor-fonts.mjs\`, which reads \`theme.yaml\`. Each folder holds WOFF2 files for the listed subsets and weights only, and the font's licence, the SIL Open Font License 1.1, in \`OFL.txt\`. Do not edit these files by hand; change \`theme.yaml\` and run \`npm run vendor-fonts\`.

| Family | Folder | Subsets | Weights | Fontsource version |
| --- | --- | --- | --- | --- |
${rows.join("\n")}
`,
);

fs.rmSync(work, { recursive: true, force: true });
console.log(`Vendored ${Object.keys(fonts).length} fonts and ${Object.keys(manifest.fontSets.sets).length} font sets.`);
