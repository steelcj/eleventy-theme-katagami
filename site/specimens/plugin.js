// Font specimens for choosing the theme's font sets in phase 4. Temporary: once the fonts
// are chosen, remove this folder, site/index.js, site/layouts/specimen.njk,
// src/{lang}/specimens/ and the @fontsource packages.
//
// Candidates come from Fontsource packages in node_modules. Only the 400 and 700 weights
// of the Latin, Latin Extended and Arabic subsets are copied, to /specimens/fonts/, and
// /specimens/fonts.css declares them with Fontsource's own unicode ranges.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import yaml from "js-yaml";

const here = path.dirname(fileURLToPath(import.meta.url));
const fontsource = "node_modules/@fontsource";
const weights = [400, 700];
const latinSubsets = ["latin", "latin-ext"];
const arabicSubsets = ["arabic"];

function familyName(id) {
  const css = fs.readFileSync(path.join(fontsource, id, "400.css"), "utf8");
  return css.match(/font-family: '([^']+)'/)[1];
}

// A package's @font-face rules for some subsets, pointing at copies of its WOFF2 files.
function fontFaces(id, subsets, files) {
  const rules = [];
  for (const weight of weights) {
    const css = fs.readFileSync(path.join(fontsource, id, `${weight}.css`), "utf8");
    for (const chunk of css.split(/(?=\/\* )/)) {
      const name = chunk.match(/^\/\* (\S+) \*\//)?.[1];
      if (!name) continue;
      const subset = name.slice(id.length + 1, -`-${weight}-normal`.length);
      if (!subsets.includes(subset)) continue;
      const file = chunk.match(/url\(\.\/files\/([^)]+\.woff2)\)/)[1];
      files.add(path.join(fontsource, id, "files", file));
      rules.push(chunk.replace(/src: [^;]+;/, `src: url(/specimens/fonts/${file}) format("woff2");`).trim());
    }
  }
  return rules;
}

export default function specimens(eleventyConfig) {
  const candidates = yaml.load(fs.readFileSync(path.join(here, "candidates.yaml"), "utf8"));
  const files = new Set();
  const faces = new Map();
  const face = (id, subsets) => {
    if (!faces.has(id)) faces.set(id, fontFaces(id, subsets, files));
  };

  // Each specimen section is one combination of heading, body and Arabic fonts.
  const sets = {};
  const rules = [];
  for (const [name, set] of Object.entries(candidates)) {
    set.latin.forEach((id) => face(id, latinSubsets));
    if (set.body) face(set.body, latinSubsets);
    set.arabic.forEach((id) => face(id, arabicSubsets));
    const combination = (heading, arabic, label) => {
      const body = set.body ?? heading;
      const id = `${name}-${label}`;
      const stack = (latin) => `"${familyName(latin)}", "${familyName(arabic)}", ${set.generic}`;
      rules.push(`.specimen--${id} {\n  --font-heading: ${stack(heading)};\n  --font-body: ${stack(body)};\n  font-family: var(--font-body);\n}`);
      return { id, label: familyName(label), heading: familyName(heading), body: familyName(body), arabic: familyName(arabic) };
    };
    sets[name] = {
      latin: set.latin.map((id) => combination(id, set.arabic[0], id)),
      arabic: set.arabic.map((id) => combination(set.latin[0], id, id)),
    };
  }

  const css = [
    "/* Generated by site/specimens/plugin.js from Fontsource packages. */",
    ...[...faces.values()].flat(),
    ".specimen {\n  padding-block: var(--space-l);\n  border-block-start: var(--rule-width) solid var(--color-rule);\n}",
    ".specimen__fonts {\n  color: var(--color-text-muted);\n  font-family: var(--font-mono);\n  font-size: var(--step--1);\n}",
    ...rules,
  ].join("\n\n");

  eleventyConfig.addGlobalData("specimens", sets);
  eleventyConfig.addTemplate("specimens-fonts.njk", `{% raw %}${css}\n{% endraw %}`, {
    permalink: "/specimens/fonts.css",
    eleventyExcludeFromCollections: true,
    layout: false,
  });
  for (const file of files) {
    eleventyConfig.addPassthroughCopy({ [file]: `specimens/fonts/${path.basename(file)}` });
  }
}
